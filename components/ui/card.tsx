import * as React from "react";

import { cn } from "@/lib/utils";

function Card({ className, ...props }: React.ComponentProps<"div">) {
  return (
    <div
      data-slot="card"
      className={cn(
        "rounded-xl border border-white/[0.06] bg-[#0a0a0a] p-6",
        className
      )}
      {...props}
    />
  );
}

